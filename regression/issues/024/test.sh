#!/usr/bin/env bash
# 024: when project stage regenerates dist/releases/apex/f<id>/f<id>.sql for an application
# change, it must also change the "-- sqlcl_checksum" line of f<id>.xml. That XML is the
# Liquibase changeset (runOnChange); if it does not change, the new application is never
# redeployed. SQLcl 26.3 computes the value from the XML itself, so it stays the same.
#
# On its own branch, readable mode:
#  1. Regenerate the deployment with this version, as a project would after upgrading:
#     remove dist/releases/apex/f<id> (the baseline controller was written by 26.1, and
#     staging over it is test 008), export the unchanged application, commit, project stage,
#     commit. Where stage does not regenerate the folder, the baseline one is put back.
#  2. The smallest real change: the title of page APEX_TITLE_PAGE (default 6, Departments),
#     made in APEX (apex import of the baseline source with the new title). Export, commit,
#     project stage.
#  3. f<id>.sql must differ from step 1 (otherwise the test proves nothing: ERROR), and the
#     sqlcl_checksum of f<id>.xml must differ too (otherwise FAIL).
source "$(dirname "$0")/../../lib/common.sh"

page=${APEX_TITLE_PAGE:-6}
new_title="Departments REG-024"
work="$RUN_DIR/024"
app_dist="dist/releases/apex/f$APEX_APP_ID"
sql_file="$TEST_REPO/$app_dist/f$APEX_APP_ID.sql"
xml_file="$TEST_REPO/$app_dist/f$APEX_APP_ID.xml"

# snapshot_hash <f.sql>: hash of the -- sqlcl_snapshot trailer stage writes at the end
snapshot_hash() {
  tail -n 5 "$1" | tr -d '\r' | sed -n 's/^-- sqlcl_snapshot .*"hash":"\([0-9a-fA-F]*\)".*/\1/p' | tail -1
}
# xml_checksum <f.xml>: value of the -- sqlcl_checksum line
xml_checksum() {
  tr -d '\r' <"$1" | sed -n 's/^-- sqlcl_checksum[[:space:]]*\([^[:space:]]*\).*/\1/p' | head -1
}
page_title() {
  sql_value "select page_title from apex_application_pages where application_id = $APEX_APP_ID and page_id = $page"
}

cleanup() {
  leave_branch
  rm -f "$RUN_DIR/apex-export.done"
  restore_apex_app "$work"
  [[ $(page_title) != "${new_title// /}" ]] || warn "page $page still has the test title after restore"
}

mkdir -p "$work"
isolate_branch 024
trap cleanup EXIT

# 1. Deployment regenerated by this version, committed (the "merged" starting point)
rm -rf "${TEST_REPO:?}/$app_dist"
fresh_apex_export "$work/export-1.log"
keep_only_apex_export
commit_all "Remove $app_dist; application $APEX_APP_ID exported (unchanged)" \
  || error "nothing to commit: $app_dist missing from the baseline?"
project_stage "$work/stage-1.log" \
  || error "project stage (regenerate) failed: $(first_error "$work/stage-1.log")"
if [[ ! -f $xml_file ]]; then
  echo "stage did not regenerate $app_dist; using the baseline one"
  restore_from_baseline "$app_dist"
fi
[[ -f $sql_file && -f $xml_file ]] || error "no f$APEX_APP_ID.sql/.xml in $app_dist after step 1"
commit_all "Stage: deployment regenerated" || true
cp "$sql_file" "$work/step1.sql"
cp "$xml_file" "$work/step1.xml"

# 2. Minimal application change: one page title, made in APEX, exported, committed, staged
baseline_apexlang_copy "$work/app" || error "no application.apx in the baseline export"
page_file=$(find "$work/app/pages" -name "$(printf 'p%05d-*.apx' "$page")" | head -1)
[[ -n $page_file ]] || error "no page $page in the baseline application source"
awk -v t="$new_title" '!done && /^[[:space:]]*title:/ { sub(/title:.*/, "title: " t); done = 1 } 1' \
  "$page_file" >"$page_file.tmp" && mv "$page_file.tmp" "$page_file"
grep -q "title: $new_title" "$page_file" || error "could not set the title in ${page_file#"$work/"}"
apex_import "$work/app" "$work/import.log" \
  || error "apex validate/import of the retitled app failed, see $work/import.log"
[[ $(page_title) == "${new_title// /}" ]] || error "page $page title not changed in APEX after import"

fresh_apex_export "$work/export-2.log"
keep_only_apex_export
commit_all "Application $APEX_APP_ID: page $page title changed" \
  || error "the title change produced no change to commit"
log="$work/stage-2.log"
if ! project_stage "$log"; then
  grep -q 'has been edited' "$log" \
    && error "project stage refuses $app_dist/f$APEX_APP_ID.xml it generated itself in step 1: $(first_error "$log")"
  error "project stage failed: $(first_error "$log")"
fi

# 3. The verdict
[[ -f $sql_file && -f $xml_file ]] || error "project stage removed $app_dist"
cmp -s "$work/step1.sql" "$sql_file" \
  && error "f$APEX_APP_ID.sql did not change after the title change; the test proves nothing"
grep -q "$new_title" "$sql_file" || warn "the new title is not in f$APEX_APP_ID.sql"

old_hash=$(snapshot_hash "$work/step1.sql") new_hash=$(snapshot_hash "$sql_file")
old_sum=$(xml_checksum "$work/step1.xml") new_sum=$(xml_checksum "$xml_file")
[[ -n $old_sum && -n $new_sum ]] || error "no sqlcl_checksum line in f$APEX_APP_ID.xml"
sql_change="f$APEX_APP_ID.sql changed (snapshot hash ${old_hash:-?} -> ${new_hash:-?})"

[[ $old_sum != "$new_sum" ]] \
  && pass "$sql_change and f$APEX_APP_ID.xml sqlcl_checksum changed ($old_sum -> $new_sum)"
fail "$sql_change but f$APEX_APP_ID.xml sqlcl_checksum stayed $old_sum: Liquibase would not redeploy the application"
